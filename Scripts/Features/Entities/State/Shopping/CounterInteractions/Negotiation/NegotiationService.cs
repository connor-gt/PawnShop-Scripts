using System.Collections.Generic;
using UnityEngine;

/// <summary>
/// Provides calculations and evaluations for NPC/player negotiations using a specified seller profile.
/// </summary>
public class NegotiationService
{
    private readonly SellerProfileModule sellerProfileModule;

    /// <summary>
    /// Gets the <see cref="SellerProfileSO"/> that this service is currently using via <see cref="SellerProfileModule"/>.
    /// </summary>
    public SellerProfileSO SellerProfile => sellerProfileModule.Profile;

    /// <summary>
    /// Creates a new <see cref="NegotiationService"/> using the specified seller profile.
    /// </summary>
    /// <param name="sellerProfileModule">The seller profile module that contains the seller profile that determines how
    /// negotiations are calculated and evaluated.</param>
    public NegotiationService(SellerProfileModule sellerProfileModule)
    {
        this.sellerProfileModule = sellerProfileModule;
    }

    /// <summary>
    /// Calculates the initial offer an NPC will make for a collection of items.
    /// <para>
    /// The starting offer is generated by multiplying the total estimated value of the items by a randomly
    /// selected value ratio within the range defined by the seller profile that was injected via the constructor.
    /// </para>
    /// <para>
    /// For example, if the ratio range of the seller profile's starting offer value ratio is 0.5 - 0.7 and the
    /// items' total estimated value is $132, then the starting offer can be anywhere from $66 - $92.
    /// </para>
    /// </summary>
    /// <param name="items">The items being negotiated over.</param>
    /// <returns>The NPC's initial offer value.</returns>
    public int CalculateStartingOffer(IReadOnlyList<Item> items)
    {
        int totalEstimatedValue = ItemServices.GetTotalEstimatedValue(items);

        float offerValueRatio = Random.Range(
            SellerProfile.StartingOfferValueRatioRange.x,
            SellerProfile.StartingOfferValueRatioRange.y
        );

        return (int)(totalEstimatedValue * offerValueRatio);
    }

    /// <summary>
    /// Evaluates the current state of a negotiation session and determines how the NPC should respond.
    /// <para>
    /// The player's offer is compared against the seller profile's acceptance and minimum acceptable value
    /// ratios to determine whether the NPC accepts, rejects, or continues negotiating.
    /// </para>
    /// </summary>
    /// <param name="session">The current negotiation session.</param>
    /// <returns>The result of the negotiation evaluation.</returns>
    public NegotiationResult EvaluateSession(NegotiationSession session)
    {
        float offerValueRatio = CalculateOfferValueRatio(session);

        if ((SellerProfile.LimitCounterOffers && session.OffersSubmitted > SellerProfile.MaxCounterOffers)
            || offerValueRatio < SellerProfile.MinimumAcceptableValueRatio)
        {
            return NegotiationResult.Reject;
        }

        // Make sure the NPC does not get a chance to randomly accept an offer that's lower than an offer they
        // previously denied (e.g., if the player offers $25, NPC denies, player then offers $20, but NPC accepts)
        if (session.PlayerOffer < session.HighestDeniedPlayerOffer)
        {
            return NegotiationResult.DenyPlayerOffer;
        }

        if (offerValueRatio >= SellerProfile.AcceptanceValueRatio || SellerProfile.AcceptanceValueRatio <= 0f)
        {
            return NegotiationResult.Accept;
        }

        // Offers below the desired ratio aren't auto‑accepted, but the closer the player's offer is to the
        // seller's desired ratio, the more likely the seller is to accept
        float difference = SellerProfile.AcceptanceValueRatio - offerValueRatio;
        float lerpValue = difference / SellerProfile.AcceptanceValueRatio;
        float acceptanceChance = Mathf.Lerp(SellerProfile.BelowDesiredAcceptanceChance, 0f, lerpValue);
        if (Random.value < acceptanceChance)
        {
            return NegotiationResult.Accept;
        }

        return NegotiationResult.DenyPlayerOffer;
    }

    /// <summary>
    /// Calculates the ratio between the player's current offer and the estimated value of the items being sold.
    /// <para>
    /// For example, an offer of $50 for an item estimated at $100 would return a value ratio of 0.5.
    /// </para>
    /// </summary>
    /// <param name="session">The current negotiation session.</param>
    /// <returns>The percentage of the item's estimated value represented by the player's offer as a decimal value.
    /// </returns>
    public float CalculateOfferValueRatio(NegotiationSession session)
    {
        int totalEstimatedValue = session.EstimatedValue;

        float offerValueRatio = 0f;
        if (totalEstimatedValue != 0)
        {
            offerValueRatio = (float)session.PlayerOffer / totalEstimatedValue;
        }

        return offerValueRatio;
    }
}
